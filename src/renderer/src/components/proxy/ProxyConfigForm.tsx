import { useState, useEffect, useRef } from 'react'
import { useTranslation } from 'react-i18next'
import { Card, CardContent, CardDescription, CardHeader, CardTitle } from '@/components/ui/card'
import { Input } from '@/components/ui/input'
import { Label } from '@/components/ui/label'
import { Button } from '@/components/ui/button'
import { Badge } from '@/components/ui/badge'
import { Switch } from '@/components/ui/switch'
import { useProxyStore } from '@/stores/proxyStore'
import { useToast } from '@/hooks/use-toast'
import { Server, AlertCircle, RefreshCw, ShieldCheck } from 'lucide-react'
import type { TlsStatus } from '@shared/types'
import { buildHttpsUrl, normalizeSanHostList, validateSanHosts } from '@shared/httpsConfig'
import {
  Dialog,
  DialogContent,
  DialogDescription,
  DialogFooter,
  DialogHeader,
  DialogTitle,
} from '@/components/ui/dialog'

interface ProxyConfigFormProps {
  onConfigChange?: () => void
}

interface FormErrors {
  port?: string
  host?: string
  httpsPort?: string
  httpsCert?: string
  httpsSan?: string
}

interface ProxyFormValues {
  port: number
  host: string
  httpsEnabled: boolean
  httpsPort: number
  httpsCertPath: string
  httpsKeyPath: string
  httpsSanHostsText: string
}

export function ProxyConfigForm({ onConfigChange }: ProxyConfigFormProps) {
  const { t } = useTranslation()
  const { proxyConfig, proxyStatus, setProxyConfig, saveAppConfig, startProxy, stopProxy, fetchProxyStatus, isLoading } = useProxyStore()
  const { toast } = useToast()

  const initialConfigRef = useRef({
    port: proxyConfig.port.toString(),
    host: proxyConfig.host,
    httpsEnabled: proxyConfig.httpsEnabled,
    httpsPort: proxyConfig.httpsPort.toString(),
    httpsCertPath: proxyConfig.httpsCertPath ?? '',
    httpsKeyPath: proxyConfig.httpsKeyPath ?? '',
    httpsSanHostsText: (proxyConfig.httpsSanHosts ?? []).join(', '),
  })

  const [formData, setFormData] = useState({
    port: proxyConfig.port.toString(),
    host: proxyConfig.host,
    httpsEnabled: proxyConfig.httpsEnabled,
    httpsPort: proxyConfig.httpsPort.toString(),
    httpsCertPath: proxyConfig.httpsCertPath ?? '',
    httpsKeyPath: proxyConfig.httpsKeyPath ?? '',
    httpsSanHostsText: (proxyConfig.httpsSanHosts ?? []).join(', '),
  })

  const [errors, setErrors] = useState<FormErrors>({})
  const [hasChanges, setHasChanges] = useState(false)
  const [showRestartDialog, setShowRestartDialog] = useState(false)
  const [isRestarting, setIsRestarting] = useState(false)
  const [tlsStatus, setTlsStatus] = useState<TlsStatus | null>(null)
  const [tlsBusy, setTlsBusy] = useState(false)

  const refreshTlsStatus = async () => {
    try {
      const status = await window.electronAPI?.tls?.getStatus?.()
      setTlsStatus(status ?? null)
    } catch {
      setTlsStatus(null)
    }
  }

  useEffect(() => {
    const newFormData = {
      port: proxyConfig.port.toString(),
      host: proxyConfig.host,
      httpsEnabled: proxyConfig.httpsEnabled,
      httpsPort: proxyConfig.httpsPort.toString(),
      httpsCertPath: proxyConfig.httpsCertPath ?? '',
      httpsKeyPath: proxyConfig.httpsKeyPath ?? '',
      httpsSanHostsText: (proxyConfig.httpsSanHosts ?? []).join(', '),
    }
    setFormData(newFormData)
    initialConfigRef.current = newFormData
    void refreshTlsStatus()
  }, [])

  // The certificate is generated by the first HTTPS start, so the install
  // button only becomes usable after the proxy reports running.
  useEffect(() => {
    void refreshTlsStatus()
  }, [proxyStatus?.isRunning])

  const validatePort = (value: string): string | undefined => {
    const port = parseInt(value, 10)
    if (isNaN(port)) return t('proxy.portMustBeNumber')
    if (port < 1 || port > 65535) return t('proxy.portRangeError')
    if (port < 1024 && port !== 80 && port !== 443) {
      return t('proxy.portPrivilege')
    }
    return undefined
  }

  const validateHost = (value: string): string | undefined => {
    if (!value.trim()) return t('proxy.bindAddressEmpty')
    const ipv4Regex = /^(\d{1,3}\.){3}\d{1,3}$/
    const ipv6Regex = /^\[?[0-9a-fA-F:]+\]?$/
    const hostnameRegex = /^[a-zA-Z0-9]([a-zA-Z0-9-]{0,61}[a-zA-Z0-9])?$/
    
    if (!ipv4Regex.test(value) && !ipv6Regex.test(value) && !hostnameRegex.test(value) && value !== 'localhost') {
      return t('proxy.invalidIpOrHostname')
    }
    return undefined
  }

  const validateHttpsPort = (value: string): string | undefined => {
    const port = parseInt(value, 10)
    if (isNaN(port)) return t('proxy.portMustBeNumber')
    if (port < 1 || port > 65535) return t('proxy.portRangeError')
    if (port === parseInt(formData.port, 10)) return t('proxy.httpsPortConflict')
    return undefined
  }

  const validateCertPair = (): string | undefined => {
    const hasCert = formData.httpsCertPath.trim() !== ''
    const hasKey = formData.httpsKeyPath.trim() !== ''
    return hasCert !== hasKey ? t('proxy.httpsCertPairRequired') : undefined
  }

  // 跨域策略不由这里配置：`AppConfig` 里没有 CORS 字段，服务端的判定（`proxy/authPolicy.ts`
  // 的 `resolveCorsOrigin`）只回显回环来源，公网 Origin 拿不到 `Access-Control-Allow-Origin`。
  // 以前这两个控件写进的是渲染层 store，用户关掉后本次会话看起来收紧了，重启回到默认，
  // 服务端行为从未变过 —— 一个不起作用的开关比没有开关更糟，所以撤下。

  const handlePortChange = (value: string) => {
    setFormData(prev => ({ ...prev, port: value }))
    const error = validatePort(value)
    setErrors(prev => ({ ...prev, port: error }))
    setHasChanges(true)
    onConfigChange?.()
  }

  const handleHostChange = (value: string) => {
    setFormData(prev => ({ ...prev, host: value }))
    const error = validateHost(value)
    setErrors(prev => ({ ...prev, host: error }))
    setHasChanges(true)
    onConfigChange?.()
  }

  const handleHttpsToggle = (checked: boolean) => {
    setFormData(prev => ({ ...prev, httpsEnabled: checked }))
    setErrors(prev => ({ ...prev, httpsPort: checked ? validateHttpsPort(formData.httpsPort) : undefined }))
    setHasChanges(true)
    onConfigChange?.()
  }

  const handleHttpsPortChange = (value: string) => {
    setFormData(prev => ({ ...prev, httpsPort: value }))
    const error = validateHttpsPort(value)
    setErrors(prev => ({ ...prev, httpsPort: error }))
    setHasChanges(true)
    onConfigChange?.()
  }

  const handleCertPathChange = (field: 'httpsCertPath' | 'httpsKeyPath', value: string) => {
    setFormData(prev => ({ ...prev, [field]: value }))
    const other = field === 'httpsCertPath' ? formData.httpsKeyPath : formData.httpsCertPath
    const error = (value.trim() !== '') !== (other.trim() !== '') ? t('proxy.httpsCertPairRequired') : undefined
    setErrors(prev => ({ ...prev, httpsCert: error }))
    setHasChanges(true)
    onConfigChange?.()
  }

  const handleSanHostsChange = (value: string) => {
    setFormData(prev => ({ ...prev, httpsSanHostsText: value }))
    const error = validateSanHosts([value]).length > 0 ? t('proxy.httpsSanInvalid') : undefined
    setErrors(prev => ({ ...prev, httpsSan: error }))
    setHasChanges(true)
    onConfigChange?.()
  }

  const runTlsTrustAction = async (kind: 'install' | 'uninstall') => {
    if (tlsBusy) return
    setTlsBusy(true)
    try {
      const result =
        kind === 'install'
          ? await window.electronAPI?.tls?.installTrust?.()
          : await window.electronAPI?.tls?.uninstallTrust?.()
      const ok = result?.ok ?? false
      toast({
        title:
          kind === 'install'
            ? ok
              ? t('proxy.httpsTrustInstalled')
              : t('proxy.httpsTrustFailed')
            : ok
              ? t('proxy.httpsTrustRemoved')
              : t('proxy.httpsTrustRemoveFailed'),
        description: result?.message,
        variant: ok ? 'default' : 'destructive',
      })
      await refreshTlsStatus()
    } catch (error) {
      toast({
        title: kind === 'install' ? t('proxy.httpsTrustFailed') : t('proxy.httpsTrustRemoveFailed'),
        description: error instanceof Error ? error.message : undefined,
        variant: 'destructive',
      })
    } finally {
      setTlsBusy(false)
    }
  }

  const handleSave = async () => {
    const portError = validatePort(formData.port)
    const hostError = validateHost(formData.host)
    const httpsPortError = formData.httpsEnabled ? validateHttpsPort(formData.httpsPort) : undefined
    const httpsCertError = formData.httpsEnabled ? validateCertPair() : undefined
    const httpsSanError =
      formData.httpsEnabled && validateSanHosts([formData.httpsSanHostsText]).length > 0
        ? t('proxy.httpsSanInvalid')
        : undefined

    if (portError || hostError || httpsPortError || httpsCertError || httpsSanError) {
      setErrors({
        port: portError,
        host: hostError,
        httpsPort: httpsPortError,
        httpsCert: httpsCertError,
        httpsSan: httpsSanError,
      })
      toast({
        title: t('proxy.validationFailed'),
        description: t('proxy.fixFormErrors'),
        variant: 'destructive',
      })
      return
    }

    const values: ProxyFormValues = {
      port: parseInt(formData.port, 10),
      host: formData.host,
      httpsEnabled: formData.httpsEnabled,
      httpsPort: parseInt(formData.httpsPort, 10),
      httpsCertPath: formData.httpsCertPath.trim(),
      httpsKeyPath: formData.httpsKeyPath.trim(),
      httpsSanHostsText: formData.httpsSanHostsText.trim(),
    }
    const listenerChanged =
      values.port !== proxyConfig.port ||
      values.host !== proxyConfig.host ||
      values.httpsEnabled !== proxyConfig.httpsEnabled ||
      values.httpsPort !== proxyConfig.httpsPort ||
      values.httpsCertPath !== (proxyConfig.httpsCertPath ?? '') ||
      values.httpsKeyPath !== (proxyConfig.httpsKeyPath ?? '') ||
      values.httpsSanHostsText !== (proxyConfig.httpsSanHosts ?? []).join(', ')

    if (listenerChanged && proxyStatus?.isRunning) {
      setShowRestartDialog(true)
      return
    }

    await performSave(values)
  }

  const performSave = async (values: ProxyFormValues): Promise<boolean> => {
    const previous = {
      port: proxyConfig.port,
      host: proxyConfig.host,
      httpsEnabled: proxyConfig.httpsEnabled,
      httpsPort: proxyConfig.httpsPort,
      httpsCertPath: proxyConfig.httpsCertPath,
      httpsKeyPath: proxyConfig.httpsKeyPath,
      httpsSanHosts: proxyConfig.httpsSanHosts,
    }
    // 界面是一栏逗号分隔的文本，落库是数组：这里折一次，读回来再显示成文本。
    const sanHosts = normalizeSanHostList([values.httpsSanHostsText])
    setProxyConfig({
      port: values.port,
      host: values.host,
      httpsEnabled: values.httpsEnabled,
      httpsPort: values.httpsPort,
      httpsCertPath: values.httpsCertPath || undefined,
      httpsKeyPath: values.httpsKeyPath || undefined,
      httpsSanHosts: sanHosts,
    })

    const success = await saveAppConfig({
      proxyPort: values.port,
      proxyHost: values.host,
      httpsEnabled: values.httpsEnabled,
      httpsPort: values.httpsPort,
      httpsCertPath: values.httpsCertPath || undefined,
      httpsKeyPath: values.httpsKeyPath || undefined,
      httpsSanHosts: sanHosts,
    })

    if (success) {
      setHasChanges(false)
      initialConfigRef.current = {
        port: values.port.toString(),
        host: values.host,
        httpsEnabled: values.httpsEnabled,
        httpsPort: values.httpsPort.toString(),
        httpsCertPath: values.httpsCertPath,
        httpsKeyPath: values.httpsKeyPath,
        httpsSanHostsText: sanHosts.join(', '),
      }
      toast({
        title: t('common.success'),
        description: t('proxy.proxyConfigUpdated'),
      })
      await refreshTlsStatus()
      return true
    }

    // 保存失败就退回界面原值：留着新值，界面显示的就是一个盘上并不存在的端口，
    // 用户会拿着它去连客户端。
    setProxyConfig(previous)
    toast({
      title: t('common.error'),
      description: t('proxy.configSaveFailed'),
      variant: 'destructive',
    })
    return false
  }

  const handleRestartAndSave = async () => {
    setIsRestarting(true)
    try {
      const values: ProxyFormValues = {
        port: parseInt(formData.port, 10),
        host: formData.host,
        httpsEnabled: formData.httpsEnabled,
        httpsPort: parseInt(formData.httpsPort, 10),
        httpsCertPath: formData.httpsCertPath.trim(),
        httpsKeyPath: formData.httpsKeyPath.trim(),
        httpsSanHostsText: formData.httpsSanHostsText.trim(),
      }

      const saved = await performSave(values)
      if (!saved) return

      await stopProxy()
      await waitForProxyToStop()

      const success = await startProxy(values.port)

      if (success) {
        toast({
          title: t('common.success'),
          description: t('proxy.proxyRestarted'),
        })
      } else {
        toast({
          title: t('common.error'),
          description: t('proxy.proxyRestartFailed'),
          variant: 'destructive',
        })
      }
      await refreshTlsStatus()
    } finally {
      setIsRestarting(false)
      setShowRestartDialog(false)
    }
  }

  /**
   * 等端口真正释放，而不是固定等 500ms。慢机器、防火墙弹窗、上游连接未收尾时，
   * 500ms 到点就 start 会撞「端口仍被占用」，界面于是停在「已停止」而配置已是新的。
   */
  const waitForProxyToStop = async (timeoutMs = 3000): Promise<void> => {
    const deadline = Date.now() + timeoutMs
    while (Date.now() < deadline) {
      await new Promise((resolve) => setTimeout(resolve, 100))
      await fetchProxyStatus()
      if (!useProxyStore.getState().proxyStatus?.isRunning) return
    }
  }

  const handleReset = () => {
    setFormData(initialConfigRef.current)
    setErrors({})
    setHasChanges(false)
  }

  const isValid = !errors.port && !errors.host && !errors.httpsPort && !errors.httpsCert && !errors.httpsSan
  const formSanHosts = normalizeSanHostList([formData.httpsSanHostsText])
  // 绑 `0.0.0.0` 时那个地址本身连不上，界面要显示的是客户端真正会敲的那个 IP。
  const httpsPreviewHost =
    formData.host === '0.0.0.0' || formData.host === '::'
      ? formSanHosts.find((host) => host !== 'localhost') ?? '127.0.0.1'
      : formData.host

  return (
    <>
      <Card>
        <CardHeader>
          <div className="flex items-center justify-between">
            <div className="flex items-center gap-2">
              <Server className="h-[15px] w-[15px] text-[var(--text-muted)]" />
              <CardTitle>{t('proxy.basicConfig')}</CardTitle>
            </div>
            {hasChanges && (
              <Badge variant="secondary" className="text-xs">
                {t('proxy.unsaved')}
              </Badge>
            )}
          </div>
          <CardDescription>{t('proxy.basicConfigDesc')}</CardDescription>
        </CardHeader>
        <CardContent className="space-y-6">
          <div className="grid gap-4 md:grid-cols-2">
            <div className="space-y-2">
              <Label htmlFor="port" className="flex items-center gap-2">
                {t('proxy.listeningPort')}
                {errors.port && (
                  <span className="text-destructive text-caption flex items-center gap-1">
                    <AlertCircle className="h-3 w-3" />
                    {errors.port}
                  </span>
                )}
              </Label>
              <Input
                id="port"
                type="number"
                placeholder="8080"
                value={formData.port}
                onChange={(e) => handlePortChange(e.target.value)}
                className={errors.port ? 'border-destructive' : ''}
              />
              <p className="text-xs text-muted-foreground">
                {t('proxy.portRange')}
              </p>
            </div>
            
            <div className="space-y-2">
              <Label htmlFor="host" className="flex items-center gap-2">
                {t('proxy.bindAddress')}
                {errors.host && (
                  <span className="text-destructive text-caption flex items-center gap-1">
                    <AlertCircle className="h-3 w-3" />
                    {errors.host}
                  </span>
                )}
              </Label>
              <Input
                id="host"
                placeholder="127.0.0.1"
                value={formData.host}
                onChange={(e) => handleHostChange(e.target.value)}
                className={errors.host ? 'border-destructive' : ''}
              />
              <p className="text-xs text-muted-foreground">
                {t('proxy.bindAddressHelp')}
              </p>
            </div>
          </div>

          <div className="space-y-4 rounded-md border border-[var(--border)] p-4">
            <div className="flex items-start justify-between gap-4">
              <div className="space-y-1">
                <Label htmlFor="https-enabled" className="flex items-center gap-2">
                  <ShieldCheck className="h-3.5 w-3.5" />
                  {t('proxy.httpsEnabled')}
                </Label>
                <p className="text-xs text-muted-foreground">{t('proxy.httpsEnabledHelp')}</p>
              </div>
              <Switch
                id="https-enabled"
                checked={formData.httpsEnabled}
                onCheckedChange={handleHttpsToggle}
              />
            </div>

            {formData.httpsEnabled && (
              <>
                <div className="grid gap-4 md:grid-cols-2">
                  <div className="space-y-2">
                    <Label htmlFor="https-port" className="flex items-center gap-2">
                      {t('proxy.httpsPort')}
                      {errors.httpsPort && (
                        <span className="text-destructive text-caption flex items-center gap-1">
                          <AlertCircle className="h-3 w-3" />
                          {errors.httpsPort}
                        </span>
                      )}
                    </Label>
                    <Input
                      id="https-port"
                      type="number"
                      placeholder="8443"
                      value={formData.httpsPort}
                      onChange={(e) => handleHttpsPortChange(e.target.value)}
                      className={errors.httpsPort ? 'border-destructive' : ''}
                    />
                    <p className="text-xs text-muted-foreground">{t('proxy.httpsPortHelp')}</p>
                  </div>

                  <div className="space-y-2">
                    <Label>{t('proxy.httpsClientUrl')}</Label>
                    <code className="block rounded bg-[var(--bg-subtle)] px-2 py-1.5 text-xs">
                      {buildHttpsUrl(httpsPreviewHost, parseInt(formData.httpsPort, 10) || 8443)}
                    </code>
                    <p className="text-xs text-muted-foreground">{t('proxy.httpsClientUrlHelp')}</p>
                  </div>
                </div>

                <div className="space-y-2">
                  <Label htmlFor="https-san-hosts" className="flex items-center gap-2">
                    {t('proxy.httpsSanHosts')}
                    {errors.httpsSan && (
                      <span className="text-destructive text-caption flex items-center gap-1">
                        <AlertCircle className="h-3 w-3" />
                        {errors.httpsSan}
                      </span>
                    )}
                  </Label>
                  <Input
                    id="https-san-hosts"
                    placeholder="192.168.1.20, 10.0.0.5"
                    value={formData.httpsSanHostsText}
                    onChange={(e) => handleSanHostsChange(e.target.value)}
                    className={errors.httpsSan ? 'border-destructive' : ''}
                  />
                  <p className="text-xs text-muted-foreground">{t('proxy.httpsSanHostsHelp')}</p>
                </div>

                <div className="space-y-2">
                  <Label>{t('proxy.httpsCertificate')}</Label>
                  {tlsStatus?.error ? (
                    <p className="text-xs text-destructive">{tlsStatus.error}</p>
                  ) : tlsStatus?.certificate ? (
                    <div className="space-y-1 text-xs text-muted-foreground">
                      <div>
                        {t('proxy.httpsCertPath')}: <code>{tlsStatus.certificate.certPath}</code>
                      </div>
                      <div>
                        {t('proxy.httpsCertValidTo')}: {tlsStatus.certificate.validTo}
                      </div>
                      <div>
                        {t('proxy.httpsCertSan')}: <code>{tlsStatus.certificate.subjectAltName}</code>
                      </div>
                      <div>
                        {t('proxy.httpsCertTrust')}:{' '}
                        {tlsStatus.trusted === null
                          ? t('proxy.httpsCertTrustUnknown')
                          : tlsStatus.trusted
                            ? t('proxy.httpsCertTrusted')
                            : t('proxy.httpsCertUntrusted')}
                      </div>
                    </div>
                  ) : (
                    <p className="text-xs text-muted-foreground">{t('proxy.httpsCertNotGenerated')}</p>
                  )}
                  {errors.httpsCert && <p className="text-xs text-destructive">{errors.httpsCert}</p>}
                  <div className="flex flex-wrap gap-2">
                    <Button
                      type="button"
                      variant="outline"
                      size="sm"
                      onClick={() => runTlsTrustAction('install')}
                      disabled={tlsBusy || !tlsStatus?.certificate}
                    >
                      {tlsBusy ? t('proxy.httpsInstalling') : t('proxy.httpsInstallTrust')}
                    </Button>
                    <Button
                      type="button"
                      variant="outline"
                      size="sm"
                      onClick={() => runTlsTrustAction('uninstall')}
                      disabled={tlsBusy || !tlsStatus?.certificate}
                    >
                      {tlsBusy ? t('proxy.httpsUninstalling') : t('proxy.httpsUninstallTrust')}
                    </Button>
                  </div>
                  <p className="text-xs text-muted-foreground">{t('proxy.httpsInstallTrustHelp')}</p>
                  <p className="text-xs text-muted-foreground">{t('proxy.httpsRemoteTrustHint')}</p>
                </div>

                <div className="grid gap-4 md:grid-cols-2">
                  <div className="space-y-2">
                    <Label htmlFor="https-cert-path">{t('proxy.httpsCertPathLabel')}</Label>
                    <Input
                      id="https-cert-path"
                      placeholder={t('proxy.httpsCertPathPlaceholder')}
                      value={formData.httpsCertPath}
                      onChange={(e) => handleCertPathChange('httpsCertPath', e.target.value)}
                    />
                  </div>
                  <div className="space-y-2">
                    <Label htmlFor="https-key-path">{t('proxy.httpsKeyPathLabel')}</Label>
                    <Input
                      id="https-key-path"
                      placeholder={t('proxy.httpsKeyPathPlaceholder')}
                      value={formData.httpsKeyPath}
                      onChange={(e) => handleCertPathChange('httpsKeyPath', e.target.value)}
                    />
                  </div>
                </div>
              </>
            )}
          </div>

          <div className="flex justify-end space-x-2 pt-4">
            <Button
              variant="outline"
              onClick={handleReset}
              disabled={!hasChanges || isLoading}
            >
              {t('common.reset')}
            </Button>
            <Button
              onClick={handleSave}
              disabled={!hasChanges || !isValid || isLoading}
            >
              {isLoading ? t('proxy.saving') : t('proxy.saveConfig')}
            </Button>
          </div>
        </CardContent>
      </Card>

      <Dialog open={showRestartDialog} onOpenChange={setShowRestartDialog}>
        <DialogContent>
          <DialogHeader>
            <DialogTitle>{t('proxy.restartRequired')}</DialogTitle>
            <DialogDescription>
              {t('proxy.restartRequiredDesc')}
            </DialogDescription>
          </DialogHeader>
          <DialogFooter>
            <Button 
              variant="outline" 
              onClick={() => setShowRestartDialog(false)}
              disabled={isRestarting}
            >
              {t('common.cancel')}
            </Button>
            <Button 
              onClick={handleRestartAndSave}
              disabled={isRestarting}
            >
              {isRestarting ? (
                <>
                  <RefreshCw className="h-4 w-4 mr-2 animate-spin" />
                  {t('proxy.restarting')}
                </>
              ) : (
                <>
                  <RefreshCw className="h-4 w-4 mr-2" />
                  {t('proxy.restartNow')}
                </>
              )}
            </Button>
          </DialogFooter>
        </DialogContent>
      </Dialog>
    </>
  )
}

export default ProxyConfigForm
