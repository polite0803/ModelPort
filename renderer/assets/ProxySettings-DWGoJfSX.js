function refKey(providerId, displayName) {
  return `${providerId}\0${displayName.toLowerCase()}`;
}
function sameRef(refs, providerId, displayName) {
  const key = refKey(providerId, displayName);
  return refs.some((ref) => refKey(ref.providerId, ref.displayName) === key);
}
function withoutRef(refs, providerId, displayName) {
  const key = refKey(providerId, displayName);
  return refs.filter((ref) => refKey(ref.providerId, ref.displayName) !== key);
}
